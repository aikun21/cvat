import ObjectState from '../object-state';
import { ObjectType } from '../enums';
import { Job, Task } from '../session';
import { getCollection } from '../annotations';
import { getFramesMeta } from '../frames';
import { Track } from '../annotations-objects/track';
import { ActionParameterType, ActionParameters } from './base-action';
import { BaseCollectionAction, CollectionActionInput, CollectionActionOutput } from './base-collection-action';

type SerializedTrack = CollectionActionInput['collection']['tracks'][0];
type SerializedTrackShape = SerializedTrack['shapes'][0];
type TrackLike = Pick<SerializedTrack, 'shapes'> & { clientID?: number };

// positions are compared with a tolerance, a keyframe generated by interpolation is restored
// from the server with the same values, but float arithmetics of another interpolation can differ slightly
const POSITION_TOLERANCE = 0.01;

export interface TrackKeyframesSummary {
    tracks: number;
    keyframes: number;
}

function liveTracks(instance: Job | Task): Record<number, Track> {
    // the action needs the interpolation of the tracks, it is implemented by the annotation objects
    return (getCollection(instance) as any).objects;
}

function liveElement(parent: Track, clientID: number): Track | undefined {
    return ((parent as any).elements as Track[] | undefined)?.find((element) => element.clientID === clientID);
}

function sortShapes(shapes: SerializedTrackShape[]): SerializedTrackShape[] {
    return [...shapes].sort((a, b) => a.frame - b.frame);
}

function closePositions(a: number[] | undefined, b: number[] | undefined): boolean {
    if (!a || !b) return a === b;
    return a.length === b.length && a.every((value, index) => Math.abs(value - b[index]) <= POSITION_TOLERANCE);
}

function sameAttributes(a: SerializedTrackShape['attributes'], b: SerializedTrackShape['attributes']): boolean {
    const values = (attributes: SerializedTrackShape['attributes']): string => attributes
        .map((attribute) => `${attribute.spec_id}:${attribute.value}`).sort().join('\n');
    return values(a) === values(b);
}

// Inserts a keyframe every N seconds into the tracks: the interpolated shape of the frame becomes a keyframe.
// Keyframes are put on the frames that are multiples of the interval, the same frames for all tracks,
// so the keyframes of different objects are on the same frames (e.g. to export only keyframes).
// Frames where an object is outside get no keyframes.
export class InsertTrackKeyframes extends BaseCollectionAction {
    #instance: Job | Task | null = null;
    #step = 1;
    #stopFrame = 0;
    public summary: TrackKeyframesSummary = { tracks: 0, keyframes: 0 };

    public async init(instance: Job | Task, parameters: Record<string, string | number>): Promise<void> {
        const meta = await getFramesMeta(instance instanceof Job ? 'job' : 'task', instance.id);
        if (!meta.fps) {
            throw new Error('The frame rate of the video is unknown');
        }

        const seconds = +parameters['Interval, seconds'];
        if (!Number.isFinite(seconds) || seconds <= 0) {
            throw new Error('The interval must be a positive number');
        }

        this.#instance = instance;
        this.#step = Math.max(1, Math.round(seconds * meta.fps));
        this.#stopFrame = instance instanceof Job ? instance.stopFrame : instance.size - 1;
        this.summary = { tracks: 0, keyframes: 0 };
    }

    public async destroy(): Promise<void> {
        this.#instance = null;
    }

    // returns shapes of the generated keyframes
    private keyframesFor(track: TrackLike, live: Track): SerializedTrackShape[] {
        const step = this.#step;
        const shapes = sortShapes(track.shapes);
        const existing = new Set(shapes.map((shape) => shape.frame));
        const { framesInfo } = live as any;
        const generated: SerializedTrackShape[] = [];

        shapes.forEach((shape, index) => {
            if (shape.outside) return;
            const end = index + 1 < shapes.length ? shapes[index + 1].frame : this.#stopFrame + 1;
            for (let frame = (Math.floor(shape.frame / step) + 1) * step; frame < end; frame += step) {
                if (existing.has(frame) || framesInfo?.isFrameDeleted(frame)) continue;
                const position = live.get(frame);
                if (position.outside) continue;
                const keyframe: SerializedTrackShape = {
                    type: shape.type,
                    frame,
                    occluded: position.occluded,
                    outside: false,
                    rotation: position.rotation,
                    z_order: position.zOrder,
                    // mutable attributes keep values of the previous keyframe
                    attributes: shape.attributes.map((attribute) => ({ ...attribute })),
                };
                if (shape.points) {
                    keyframe.points = [...position.points];
                }
                generated.push(keyframe);
            }
        });

        return generated;
    }

    public async run(input: CollectionActionInput): Promise<CollectionActionOutput> {
        const { collection: { tracks }, onProgress, cancelled } = input;
        const objects = liveTracks(this.#instance as Job | Task);
        const created: SerializedTrack[] = [];
        const deleted: SerializedTrack[] = [];

        for (const [index, track] of tracks.entries()) {
            if (cancelled()) break;
            const live = objects[track.clientID as number];
            if (!live) continue;

            let count = 0;
            const elements = (track.elements ?? []).map((element) => {
                const liveChild = liveElement(live, element.clientID as number);
                if (!liveChild) return element;
                const added = this.keyframesFor(element, liveChild);
                count += added.length;
                return { ...element, shapes: sortShapes([...element.shapes, ...added]) };
            });

            let { shapes } = track;
            if (track.elements?.length) {
                // a skeleton keyframe is a keyframe of the skeleton and of its points
                const frames = new Set(shapes.map((shape) => shape.frame));
                const added = elements.flatMap((element) => element.shapes)
                    .map((shape) => shape.frame).filter((frame) => !frames.has(frame));
                const sorted = sortShapes(shapes);
                shapes = sortShapes([...shapes, ...[...new Set(added)].map((frame) => {
                    const previous = [...sorted].reverse().find((shape) => shape.frame < frame) ?? sorted[0];
                    return {
                        ...previous, id: undefined, frame, outside: false,
                    };
                })]);
            } else {
                const added = this.keyframesFor(track, live);
                count += added.length;
                shapes = sortShapes([...shapes, ...added]);
            }

            if (count) {
                created.push({ ...track, shapes, elements });
                deleted.push(track);
                this.summary.tracks += 1;
                this.summary.keyframes += count;
            }
            onProgress('Inserting keyframes', ((index + 1) / tracks.length) * 100);
        }

        return {
            created: { shapes: [], tags: [], tracks: created },
            deleted: { shapes: [], tags: [], tracks: deleted },
        };
    }

    public applyFilter(
        input: Pick<CollectionActionInput, 'collection' | 'frameData'>,
    ): CollectionActionInput['collection'] {
        return { shapes: [], tags: [], tracks: input.collection.tracks };
    }

    public isApplicableForObject(objectState: ObjectState): boolean {
        return objectState.objectType === ObjectType.TRACK;
    }

    public get name(): string {
        return 'Insert track keyframes at intervals';
    }

    public get parameters(): ActionParameters | null {
        return {
            'Interval, seconds': {
                type: ActionParameterType.NUMBER,
                values: ['0.01', '3600', '0.5'],
                defaultValue: '1',
            },
        };
    }
}

// Removes the keyframes that do not change the tracks: the shape is the same as the interpolation
// between the neighbouring keyframes (or as the previous keyframe for the last one), with the same
// attributes, occlusion and z order. This removes all keyframes inserted at intervals,
// the first keyframes, keyframes where objects become outside or visible again and
// keyframes that were edited are kept.
export class RemoveRedundantTrackKeyframes extends BaseCollectionAction {
    #instance: Job | Task | null = null;
    public summary: TrackKeyframesSummary = { tracks: 0, keyframes: 0 };

    public async init(instance: Job | Task): Promise<void> {
        this.#instance = instance;
        this.summary = { tracks: 0, keyframes: 0 };
    }

    public async destroy(): Promise<void> {
        this.#instance = null;
    }

    // returns the kept shapes
    private reduce(track: TrackLike, live: Track | undefined, hasPoints: boolean): SerializedTrackShape[] {
        const shapes = sortShapes(track.shapes);
        const kept: SerializedTrackShape[] = [];

        shapes.forEach((shape, index) => {
            const previous = kept[kept.length - 1];
            if (!previous || shape.outside || previous.outside ||
                shape.occluded !== previous.occluded || shape.z_order !== previous.z_order ||
                !sameAttributes(shape.attributes, previous.attributes)
            ) {
                kept.push(shape);
                return;
            }

            if (hasPoints && live) {
                const next = shapes[index + 1];
                const toPosition = (value: SerializedTrackShape): object => ({
                    points: value.points,
                    rotation: value.rotation,
                    occluded: value.occluded,
                    zOrder: value.z_order,
                    outside: value.outside,
                });
                const expected = next ? (live as any).interpolatePosition(
                    toPosition(previous),
                    toPosition(next),
                    (shape.frame - previous.frame) / (next.frame - previous.frame),
                ) : toPosition(previous);

                if (!closePositions(expected.points, shape.points) ||
                    Math.abs((expected.rotation ?? 0) - (shape.rotation ?? 0)) > POSITION_TOLERANCE
                ) {
                    kept.push(shape);
                }
            }
            // a skeleton keyframe without own changes is redundant, its points are checked separately
        });

        return kept;
    }

    public async run(input: CollectionActionInput): Promise<CollectionActionOutput> {
        const { collection: { tracks }, onProgress, cancelled } = input;
        const objects = liveTracks(this.#instance as Job | Task);
        const created: SerializedTrack[] = [];
        const deleted: SerializedTrack[] = [];

        for (const [index, track] of tracks.entries()) {
            if (cancelled()) break;
            const live = objects[track.clientID as number];
            if (!live) continue;

            let removed = 0;
            const elements = (track.elements ?? []).map((element) => {
                const shapes = this.reduce(element, liveElement(live, element.clientID as number), true);
                removed += element.shapes.length - shapes.length;
                return { ...element, shapes };
            });

            let shapes: SerializedTrackShape[];
            if (track.elements?.length) {
                // skeleton keyframes are kept where any of its points has a keyframe
                const elementFrames = new Set(elements.flatMap((element) => element.shapes.map((s) => s.frame)));
                const reduced = new Set(this.reduce(track, live, false).map((shape) => shape.frame));
                shapes = sortShapes(track.shapes)
                    .filter((shape) => reduced.has(shape.frame) || elementFrames.has(shape.frame));
            } else {
                shapes = this.reduce(track, live, true);
                removed += track.shapes.length - shapes.length;
            }

            if (removed) {
                created.push({ ...track, shapes, elements });
                deleted.push(track);
                this.summary.tracks += 1;
                this.summary.keyframes += removed;
            }
            onProgress('Removing keyframes', ((index + 1) / tracks.length) * 100);
        }

        return {
            created: { shapes: [], tags: [], tracks: created },
            deleted: { shapes: [], tags: [], tracks: deleted },
        };
    }

    public applyFilter(
        input: Pick<CollectionActionInput, 'collection' | 'frameData'>,
    ): CollectionActionInput['collection'] {
        return { shapes: [], tags: [], tracks: input.collection.tracks };
    }

    public isApplicableForObject(objectState: ObjectState): boolean {
        return objectState.objectType === ObjectType.TRACK;
    }

    public get name(): string {
        return 'Remove redundant track keyframes';
    }

    public get parameters(): ActionParameters | null {
        return null;
    }
}
